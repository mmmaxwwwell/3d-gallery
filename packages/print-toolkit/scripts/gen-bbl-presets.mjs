/**
 * Generate src/bbl-presets.generated.ts: the Bambu Lab X1 Carbon machine
 * preset, AMS filament presets and process presets for it, from an
 * OrcaSlicer source tree. The process presets carry the X1C's speeds and
 * accelerations; without them libslic3r falls back to its generic defaults
 * (500 mm/s², 60 mm/s walls) and a plate takes twice as long.
 *
 * Bambu's machine G-code is a template full of slicer placeholders, and each
 * Orca release renames some (2.3.2's X1C start G-code reads
 * `flush_volumetric_speeds`, which 2.3.1 doesn't have). A preset only slices
 * on the libslic3r it was written for, so the gallery carries the profiles
 * from the same Orca release as its slicer WASM — rebuild this whenever
 * `assets/libslic3r.wasm` moves to another Orca version.
 *
 * Usage:
 *   node scripts/gen-bbl-presets.mjs <path-to-OrcaSlicer-source>
 *
 * Any checkout of the WASM's Orca version works
 * (`git clone --depth 1 -b v2.3.1 https://github.com/SoftFever/OrcaSlicer`).
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', 'src', 'bbl-presets.generated.ts');

const PRINTERS = ['Bambu Lab X1 Carbon 0.4 nozzle'];
const FILAMENTS = [
  'Bambu PLA Basic @BBL X1C',
  'Bambu PETG HF @BBL X1C',
  'Bambu TPU for AMS @BBL X1C',
];

// One per layer height the gallery offers; a slice takes the nearest.
const PROCESSES = [
  '0.20mm Standard @BBL X1C',
  '0.28mm Extra Draft @BBL X1C',
];
const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/gen-bbl-presets.mjs <OrcaSlicer source>');
  process.exit(1);
}
const root = join(src, 'resources', 'profiles', 'BBL');
const version = /set\(SoftFever_VERSION "([^"]+)"\)/.exec(readFileSync(join(src, 'version.inc'), 'utf8'))?.[1];
if (!version) throw new Error(`No SoftFever_VERSION in ${src}/version.inc`);

/** name → preset JSON, for every machine and filament preset in the vendor dir. */
const byName = new Map();
function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (entry.name.endsWith('.json')) {
      const json = JSON.parse(readFileSync(path, 'utf8'));
      if (typeof json.name === 'string') byName.set(json.name, json);
    }
  }
}
walk(join(root, 'machine'));
walk(join(root, 'filament'));
walk(join(root, 'process'));

/** The preset and its parents, own file first, root last — the shape the gallery stores. */
function chain(name) {
  const out = [];
  for (let n = name; n;) {
    const json = byName.get(n);
    if (!json) throw new Error(`Missing preset "${n}" (inherited by "${name}")`);
    out.push(n);
    n = json.inherits;
  }
  return out;
}

const presets = {};
const entry = (name) => {
  const names = chain(name);
  for (const n of names) presets[n] = byName.get(n);
  return names;
};
const machineModel = (name) => {
  const model = byName.get(name).printer_model ?? chain(name).map((n) => byName.get(n).printer_model).find(Boolean);
  const vendorModel = JSON.parse(readFileSync(join(root, 'machine', `${model}.json`), 'utf8'));
  return { model, modelId: vendorModel.model_id };
};

const data = {
  orcaVersion: version,
  printers: PRINTERS.map((name) => ({ name, ...machineModel(name), chain: entry(name) })),
  filaments: FILAMENTS.map((name) => ({ name, chain: entry(name) })),
  processes: PROCESSES.map((name) => {
    const names = entry(name);
    const layerHeight = names.map((n) => byName.get(n).layer_height).find((v) => v !== undefined);
    return { name, layerHeight: Number(layerHeight), chain: names };
  }),
  presets,
};

writeFileSync(OUT, `// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by scripts/gen-bbl-presets.mjs from OrcaSlicer ${version}. Do not edit.
// The presets are Bambu Lab's, as OrcaSlicer ships them (AGPL-3.0).

import type { BblPresetBundle } from './bbl-presets.js';

export const BBL_PRESETS: BblPresetBundle = ${JSON.stringify(data, null, 1)};
`);
console.log(`Wrote ${OUT}: ${Object.keys(presets).length} presets from Orca ${version}`);
